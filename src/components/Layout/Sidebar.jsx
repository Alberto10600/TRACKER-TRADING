export default function Sidebar({ account }) {
  const [collapsed, setCollapsed] = useState(false)
  const location = useLocation()

  return (
    <aside
      className={`flex flex-col bg-bg-secondary border-r border-border transition-all duration-300 ${
        collapsed ? 'w-16' : 'w-56'
      }`}
    >
      {/* Logo */}
      <div className="flex items-center gap-3 px-4 py-5 border-b border-border drag-region">
        <div className="w-8 h-8 rounded-lg bg-gradient-to-br from-accent-blue to-accent-cyan flex items-center justify-center flex-shrink-0">
          <span className="text-white font-bold text-sm">TT</span>
        </div>
        {!collapsed && (
          <div className="min-w-0">
            <p className="text-text-primary font-semibold text-sm truncate">Trading Tracker</p>
            <p className="text-text-muted text-xs truncate">Pro</p>
          </div>
        )}
      </div>

      {/* Account info */}
      {!collapsed && account && (
        <div className="mx-3 mt-3 p-3 bg-bg-tertiary rounded-lg border border-border">
          <p className="text-text-muted text-xs">Cuenta</p>
          <p className="text-text-primary text-sm font-medium truncate">{account.account_name}</p>
          <p className="text-text-muted text-xs mt-1">{account.broker} · {account.currency}</p>
        </div>
      )}

      {/* Navigation */}
      <nav className="flex-1 px-2 py-3 space-y-1">
        {NAV_ITEMS.map(({ path, label, icon: Icon, highlight }) => (
          <NavLink
            key={path}
            to={path}
            className={({ isActive }) =>
              `flex items-center gap-3 px-3 py-2.5 rounded-lg transition-all duration-150 text-sm group ${
                isActive
                  ? 'bg-accent-blue/10 text-accent-blue border border-accent-blue/20'
                  : highlight
                    ? 'text-yellow-400 hover:bg-yellow-500/10 hover:text-yellow-300 border border-yellow-500/10'
                    : 'text-text-secondary hover:bg-bg-hover hover:text-text-primary'
              }`
            }
          >
            <Icon className="w-5 h-5 flex-shrink-0" />
            {!collapsed && <span className="truncate">{label}</span>}
          </NavLink>
        ))}
      </nav>

      {/* Bottom */}
      <div className="px-2 pb-3 space-y-1 border-t border-border pt-3">
        {BOTTOM_ITEMS.map(({ path, label, icon: Icon }) => (
          <NavLink
            key={path}
            to={path}
            className={({ isActive }) =>
              `flex items-center gap-3 px-3 py-2.5 rounded-lg transition-all duration-150 text-sm ${
                isActive
                  ? 'bg-accent-blue/10 text-accent-blue border border-accent-blue/20'
                  : 'text-text-secondary hover:bg-bg-hover hover:text-text-primary'
              }`
            }
          >
            <Icon className="w-5 h-5 flex-shrink-0" />
            {!collapsed && <span className="truncate">{label}</span>}
          </NavLink>
        ))}

        <button
          onClick={() => setCollapsed(!collapsed)}
          className="w-full flex items-center gap-3 px-3 py-2.5 rounded-lg text-text-muted hover:bg-bg-hover hover:text-text-secondary transition-all duration-150 text-sm"
        >
          <IconChevron className={`w-5 h-5 flex-shrink-0 transition-transform ${collapsed ? 'rotate-180' : ''}`} />
          {!collapsed && <span>Contraer</span>}
        </button>
      </div>
    </aside>
  )
}

